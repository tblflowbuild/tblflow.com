/**
 * Hero tour (HeroTour.astro): five short scenes that explain TblFlow to a
 * first-time visitor. One fictional story runs through them: 12 overdue
 * invoices, chased by an assistant, then by an agent, sent once Finance
 * approves. `{n}` and `{name}` are filled in by the component.
 */
import type { Locale } from '@/config';

export interface HeroTourScene {
  /** Scene title. */
  h: string;
  /** One-sentence explanation. */
  p: string;
  /** Concrete example. */
  ex: string;
  /** What the illustration shows, for screen readers. */
  alt: string;
}

export interface HeroTourStrings {
  pills: [string, string, string, string, string];
  scenes: [HeroTourScene, HeroTourScene, HeroTourScene, HeroTourScene, HeroTourScene];
  pause: string;
  play: string;
  replay: string;
  region: string;
  /** The generic "Files" tool tile. */
  files: string;
  /** What Sheets, Files and Notion become: tables, documents, pages. */
  replaced: [string, string, string];
  joined: string;
  swapped: string;
  legendReplaced: string;
  legendKept: string;
  views: [string, string, string];
  /** Customer, invoice, amount, status. */
  cols: [string, string, string, string];
  /** Paid, overdue. */
  status: [string, string];
  moreLateRow: string;
  moreLateCard: string;
  invoice: string;
  /** Customer, amount, due date, status. */
  fields: [string, string, string, string];
  save: string;
  providerLabel: string;
  providerChosen: string;
  moreProviders: string;
  ask: string;
  todo: [string, string, string];
  /** Name and trigger of the reminders, payments and requests agents. */
  agents: [[string, string], [string, string], [string, string]];
  agentState: { idle: string; run: string; wait: string; done: string };
  log: [string, string, string, string];
  /** Management, operations, finance, team. */
  roles: [string, string, string, string];
  apprQ: string;
  mail: string;
  no: string;
  yes: string;
  doneStrong: string;
  doneRest: string;
}

